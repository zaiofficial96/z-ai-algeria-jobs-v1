export function getWilayaName(code: number, locale: 'ar' | 'fr' | 'en'): string {
  const w = wilayas.find((w) => w.code === code);
  return w ? w.name[locale] : '';
}

export function getWilayaByCode(code: number): Wilaya | undefined {
  return wilayas.find((w) => w.code === code);
}

export function getPopularWilayas(): Wilaya[] {
  return wilayas.filter((w) => w.popular);
}
